-- Create guides table for editable instructions
CREATE TABLE public.guides (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  guide_key text NOT NULL, -- 'general', 'executor', 'admin'
  title text NOT NULL,
  sections jsonb NOT NULL DEFAULT '[]', -- array of {title, content: string[]}
  sort_order integer NOT NULL DEFAULT 0,
  updated_at timestamp with time zone NOT NULL DEFAULT now(),
  updated_by uuid
);

ALTER TABLE public.guides ENABLE ROW LEVEL SECURITY;

-- Everyone can read guides
CREATE POLICY "Everyone can view guides"
ON public.guides FOR SELECT
USING (true);

-- Only admins can manage guides
CREATE POLICY "Admins can manage guides"
ON public.guides FOR ALL
USING (has_role(auth.uid(), 'admin'::app_role))
WITH CHECK (has_role(auth.uid(), 'admin'::app_role));

